/** How a source may be used, decided when it was investigated (not at run time). */
export type SourceEligibility =
    /** Public, documented, terms checked: may be switched on. */
    | "eligible"
    /** Works and is documented, but the owner should confirm the terms fit their use before switching it on. */
    | "awaiting_verification"
    /** Needs a free developer key the owner registers for. */
    | "needs_registration"
    /** Exists, but use needs the provider's permission. */
    | "restricted"
    /** No permitted machine-readable interface was found. */
    | "unsupported";

export const SOURCE_STATUSES = [
    "active",
    "awaiting_verification",
    "needs_registration",
    "disabled",
    "unavailable",
    "restricted",
    "unsupported",
    "stale",
    "error",
] as const;
export type SourceStatus = (typeof SOURCE_STATUSES)[number];

