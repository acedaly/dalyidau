// The Intelligence Centre's source registry (docs/INTELLIGENCE_SOURCES.md): every public dataset
// that was investigated, whether it is used, and why. Shared by the Worker and the browser, so it
// holds nothing secret: endpoint labels are shown to signed-in people, credentials never.
//
// A source with an adapter can be switched on by an owner or admin (Sources page). It is reported
// Active only after a genuine retrieval has been parsed and validated; until then it says
// "Awaiting verification". Sources without an adapter are listed so the registry says plainly what
// is restricted, unsupported or waiting for registration, instead of leaving it out.

