// Generates src/styles/wedding-theme.generated.css from src/styles/theme.css.
//
// Untitled UI's semantic tokens (bg-primary, text-secondary, border-brand…) are CSS variables that
// point at palette variables, e.g. --background-color-primary: var(--color-bg-primary). Custom
// properties resolve where they are declared, so overriding the palette on a wrapper element is not
// enough: every token that refers to the palette has to be re-declared on that wrapper too. This
// script copies those declarations (and the light value of everything dark mode overrides) into a
// `.wedding-theme` rule, so the wedding website re-roots the whole token tree on its own palette.
//
// Run after updating theme.css:  node scripts/build-wedding-theme.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const css = readFileSync(join(root, "src/styles/theme.css"), "utf8");

const block = (source, opener) => {
    const start = source.indexOf(opener);
    if (start < 0) throw new Error(`Couldn't find ${opener}`);
    let depth = 0;
    for (let i = source.indexOf("{", start); i < source.length; i++) {
        if (source[i] === "{") depth++;
        if (source[i] === "}" && --depth === 0) return source.slice(source.indexOf("{", start) + 1, i);
    }
    throw new Error(`Unclosed ${opener}`);
};

const declarations = (body) => {
    const out = new Map();
    // Skip nested blocks (keyframes) before reading declarations.
    const flat = body.replace(/@keyframes[^{]+\{(?:[^{}]*\{[^{}]*\})*[^{}]*\}/g, "");
    for (const match of flat.matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)) out.set(match[1], match[2].trim().replace(/\s+/g, " "));
    return out;
};

const light = declarations(block(css, "@theme"));
const dark = declarations(block(css, ".dark-mode"));

const keep = new Map();
for (const [name, value] of light) {
    if (value.includes("var(") || dark.has(name)) keep.set(name, value);
}

const body = [...keep].map(([name, value]) => `    ${name}: ${value};`).join("\n");
const out = `/* Generated by scripts/build-wedding-theme.mjs from theme.css. Do not edit by hand. */
/* Re-declares every semantic token on .wedding-theme so it resolves against the wedding palette. */
.wedding-theme {
${body}
}
`;
writeFileSync(join(root, "src/styles/wedding-theme.generated.css"), out);
console.log(`Wrote ${keep.size} declarations to src/styles/wedding-theme.generated.css`);
